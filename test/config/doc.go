// Package config は `.github/dependabot.yml` と `.github/workflows/*.yml` が
// 満たすべき不変条件を検査する。
//
// 「設定ファイルだからテストは書けない」で済ませないための場所である
// (憲章 原則 III)。本機能の要件のうち機械的に検査できるものをここに置き、
// 後から緩める変更が差分として現れるようにする。文書の記述だけでは、
// 「便利だから」自動マージを足す変更や「失敗が邪魔だから」検査を飛ばす
// 変更を止められない。
//
// # 検査する範囲
//
//   - 待機期間が 5 日であること (FR-002)。省略は既定 3 日に緩むため失敗させる
//   - 3 種別 (gomod / github-actions / docker) が揃っていること (FR-004)
//   - 種別ごとに groups があり提案がまとめられること (FR-005)
//   - 提案数の上限が既定 (5) より狭いこと (FR-008)
//   - メジャー版を ignore していないこと (FR-007)
//   - registries が無いこと。dpf-go は公開済みで資格情報を要さない
//   - 自動マージを行う仕組みが存在しないこと (FR-009)
//   - 秘密情報を要する検査が条件付きで飛ばされていないこと (FR-014)
//
// # 検査しない範囲
//
// リポジトリ設定は作業ツリーに現れないため、ここでは検査できない。
//
//   - Dependabot alerts / security updates の有効化 (FR-003、SC-003)
//   - ブランチ保護 (必須検査とレビュー承認) (FR-009、FR-010)
//
// **この 2 つは quickstart.md の確認手順で人が確かめる。** 検査できない範囲が
// あること自体を隠さないために、ここに明記する (原則 V)。とくに
// security updates が無効だと、dependabot.yml をどう書いても SC-003
// (脆弱性の修正が公開から 1 日以内に提案される) は成立しない。
//
// # 対象が空のときは失敗させる
//
// 設定ファイルが無い、ワークフローが 1 本も見つからない、といった場合は
// エラーとして扱う。「対象がないので何も検査しない」で通すと、ファイルを
// 消すだけで検査を無効化でき、消したことに気付けない (原則 VI)。
//
// 置き場所を test/contract、test/docs と揃えているのは、go test ./... と
// make all に自動で乗せるためである。独立したスクリプトにすると make all から
// 漏れる。
