// Package docs は docs/reference.md の記述が実装と一致していることを検査する。
//
// 文書は人が書き、実装から取り出した事実と突き合わせる。文書を実装から
// 生成しない。文書の価値の大半は散文にあり (Vault が読むフィールド名、
// --dpf-token-secret-endpoint の供給元ごとの意味、AWS で kms:Decrypt が要る
// 条件)、これらは実装から機械的に導けないためである。
//
// # 検査する範囲
//
// 検査するのは、印 (<!-- reference:名前 -->) の付いた表に限る。印には 2 つの
// 役目がある。解析器に対象を伝えることと、**読み手に「ここは機械的に守られて
// いる」と示す**ことである。
//
//	flags               設定項目の名前と既定値
//	secret-managers     シークレット管理サービスの名前
//	metrics             計測値の系列名
//	dpf-operations      operation ラベルの値
//	record-types        対応レコード種別
//	endpoints-provider  provider リスナーの経路
//	endpoints-exposed   exposed リスナーの経路
//
// # 検査しない範囲
//
// 印のない記述は人が保つ。認証の解決順、必要な権限、格納手順、意味の説明、
// エラーの分類、既知の制限が該当する。経路については**方法 (メソッド) を
// 検査しない**。登録の形と表の書き方が一致しないため、経路の文字列のみを見る。
//
// **トークンが読まれる位置 (値全体か、特定のフィールドか) は検査できない。**
// 依存ライブラリの既定値であり、こちらのコードには「オプションを渡していない」
// ことしか現れない。依存の版を固定していることが緩和である。
//
// # 印が欠けた場合
//
// **失敗する。** 「対象がないので何も検査しない」で通すと、印を消すだけで
// 検査を無効化でき、表ごと消しても気付けない。期待する印の一覧は本パッケージが
// 持ち、文書側に持たせない。検査を減らすには本パッケージの差分が要る。
